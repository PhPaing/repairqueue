const dictionaries: Record<Language, Dict> = { en, th };

export function t(lang: Language, key: string, params?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

/** Both languages for a key - used where labels must be bilingual (TH + EN). */
export function tBoth(
  lang: Language,
  key: string,
  params?: Record<string, string | number>,
): { main: string; sub: string } {
  const other: Language = lang === 'th' ? 'en' : 'th';
  return { main: t(lang, key, params), sub: t(other, key, params) };
}
